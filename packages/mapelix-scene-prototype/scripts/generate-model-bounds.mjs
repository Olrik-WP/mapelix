import { readFile, writeFile } from "node:fs/promises";

import { blockModelParts, modelCatalog } from "../src/blocks/block-models.ts";

// Run with Node 24 (or --experimental-strip-types on Node 22). Existing ids are append-only.
const output = new URL("../src/model-boxes.ts", import.meta.url);
let codes = [];
try {
  const source = await readFile(output, "utf8");
  codes = source
    .match(/MODEL_BOUND_CODES = (\[[\s\S]*?\])/)[1]
    .match(/\d+/g)
    .map(Number);
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
for (const model of modelCatalog())
  for (const { bounds } of blockModelParts(model)) {
    const code =
      bounds.reduce((value, coordinate, index) => value | (coordinate << (index * 5)), 0) >>> 0;
    if (!codes.includes(code)) codes.push(code);
  }
if (codes.length > 192) throw new Error("The compatible model bounds catalog exceeds 192 entries");
await writeFile(
  output,
  `/** Append-only cuboid bounds, generated by scripts/generate-model-bounds.mjs. */
export const MODEL_BOUND_CODES = ${JSON.stringify(codes)} as const;

/** Bounds in sixteenths: low xyz, high xyz. Each coordinate occupies five bits. */
export type ModelBounds = readonly [number, number, number, number, number, number];
const ids = new Map<number, number>(MODEL_BOUND_CODES.map((code, index) => [code, index]));

export function modelBoxId(bounds: ModelBounds): number {
  const code = bounds.reduce((value, coordinate, index) => value | (coordinate << (index * 5)), 0) >>> 0;
  const id = ids.get(code);
  if (id === undefined) throw new RangeError("Unregistered model bounds: " + bounds.join(","));
  return id;
}

export function modelBoxBounds(id: number): ModelBounds {
  const code = MODEL_BOUND_CODES[id];
  if (code === undefined) throw new RangeError("Invalid model box " + id);
  return [code & 31, (code >>> 5) & 31, (code >>> 10) & 31, (code >>> 15) & 31, (code >>> 20) & 31, (code >>> 25) & 31];
}
`,
);
console.log(`Registered ${codes.length} model boxes`);
